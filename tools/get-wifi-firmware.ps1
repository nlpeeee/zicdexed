Invoke-WebRequest "$base/cypress/cyfmac43455-sdio-minimal.bin" -OutFile "firmware\brcmfmac43455-sdio.raspberrypi,5-model-b.bin"
Invoke-WebRequest "$base/brcm/brcmfmac43455-sdio.txt" -OutFile "firmware\brcmfmac43455-sdio.raspberrypi,5-model-b.txt"

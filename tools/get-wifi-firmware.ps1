# Downloads the Pi Zero 2 W WiFi firmware into .\firmware (run from this folder in PowerShell)
$ErrorActionPreference="Stop"
New-Item -ItemType Directory -Force firmware | Out-Null
$base="https://github.com/RPi-Distro/firmware-nonfree/raw/c9d3ae6584ab79d19a4f94ccf701e888f9f87a53/debian/config/brcm80211"
Invoke-WebRequest "$base/cypress/cyfmac43430-sdio.bin" -OutFile "firmware\brcmfmac43430-sdio.bin"
Invoke-WebRequest "$base/brcm/brcmfmac43430-sdio.txt" -OutFile "firmware\brcmfmac43430-sdio.txt"
Invoke-WebRequest "$base/cypress/cyfmac43430-sdio.clm_blob" -OutFile "firmware\brcmfmac43430-sdio.clm_blob"
Invoke-WebRequest "$base/brcm/brcmfmac43436-sdio.bin" -OutFile "firmware\brcmfmac43436-sdio.bin"
Invoke-WebRequest "$base/brcm/brcmfmac43436-sdio.txt" -OutFile "firmware\brcmfmac43436-sdio.txt"
Invoke-WebRequest "$base/brcm/brcmfmac43436-sdio.clm_blob" -OutFile "firmware\brcmfmac43436-sdio.clm_blob"
Invoke-WebRequest "$base/brcm/brcmfmac43436s-sdio.bin" -OutFile "firmware\brcmfmac43436s-sdio.bin"
Invoke-WebRequest "$base/brcm/brcmfmac43436s-sdio.txt" -OutFile "firmware\brcmfmac43436s-sdio.txt"
Invoke-WebRequest "$base/cypress/cyfmac43455-sdio-minimal.bin" -OutFile "firmware\brcmfmac43455-sdio.bin"
Invoke-WebRequest "$base/brcm/brcmfmac43455-sdio.txt" -OutFile "firmware\brcmfmac43455-sdio.txt"
Invoke-WebRequest "$base/cypress/cyfmac43455-sdio.clm_blob" -OutFile "firmware\brcmfmac43455-sdio.clm_blob"
Invoke-WebRequest "$base/brcm/brcmfmac43456-sdio.bin" -OutFile "firmware\brcmfmac43456-sdio.bin"

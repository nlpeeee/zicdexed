#!/usr/bin/env python3
"""Pre-render the Inter faces used by the UI to 4-bit alpha bitmaps.

Usage: fontgen.py <out .cpp>
Needs Inter (SIL OFL) installed in /usr/share/fonts/opentype/inter/ and Pillow.
The same faces and sizes are used by tools/mockups/render_mockups.py, so the
firmware screen matches the mockups. The generated file is committed; rerun
this only when a face or size changes.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

INTER = "/usr/share/fonts/opentype/inter/"

# name, face, px size, first char, last char
FONTS = [
    ("Lbl",   "Inter-SemiBold",         9, 32, 126),
    ("Small", "Inter-Medium",          10, 32, 126),
    ("Tiny",  "Inter-Medium",           9, 32, 126),
    ("Body",  "Inter-SemiBold",        12, 32, 126),
    ("Title", "InterDisplay-Bold",     15, 32, 126),
    ("Val",   "InterDisplay-Bold",     21, 32, 126),
    ("Head",  "InterDisplay-Black",    18, 32, 126),
    ("Big",   "InterDisplay-Black",    30, 32, 126),
    ("Huge",  "InterDisplay-Black",    44, 32, 95),   # upper case only; lower case is folded
]

PAD = 8


def render(face, size, first, last):
    font = ImageFont.truetype(INTER + face + ".otf", size)
    glyphs, blob = [], bytearray()
    asc, desc = font.getmetrics()
    for code in list(range(first, last + 1)) + [0xB7]:     # plus the middle dot, stored after the last glyph
        ch = chr(code)
        adv = font.getlength(ch)
        im = Image.new("L", (size * 2 + 2 * PAD, size * 2 + 2 * PAD), 0)
        ImageDraw.Draw(im).text((PAD, PAD), ch, font=font, fill=255)
        bb = im.getbbox()
        if bb is None:
            glyphs.append((len(blob), 0, 0, 0, 0, round(adv * 16)))
            continue
        crop = im.crop(bb)
        w, h = crop.size
        px = [min(15, (v + 8) // 17) for v in crop.tobytes()]
        if len(px) % 2:
            px.append(0)
        off = len(blob)
        for i in range(0, len(px), 2):
            blob.append((px[i] << 4) | px[i + 1])
        glyphs.append((off, w, h, bb[0] - PAD, bb[1] - PAD, round(adv * 16)))
    return glyphs, blob, asc + desc


def main():
    out = open(sys.argv[1], "w")
    out.write("// Generated by tools/fontgen.py from Inter (SIL Open Font License). Do not edit.\n")
    out.write('#include "zicfont.h"\n\nnamespace zic {\n\n')
    for name, face, size, first, last in FONTS:
        glyphs, blob, lh = render(face, size, first, last)
        out.write(f"// {face} {size}px, chars {first}..{last}\n")
        out.write(f"static const uint8_t k{name}Bits[] = {{\n")
        for i in range(0, len(blob), 24):
            out.write("\t" + ",".join(str(b) for b in blob[i:i + 24]) + ",\n")
        if not blob:
            out.write("\t0\n")
        out.write("};\n")
        out.write(f"static const Glyph k{name}Glyphs[] = {{\n")
        for g in glyphs:
            out.write("\t{%d,%d,%d,%d,%d,%d},\n" % g)
        out.write("};\n")
        out.write(f"const Font f{name} = {{k{name}Glyphs, k{name}Bits, {first}, {last}, {lh}}};\n\n")
    out.write("} // namespace zic\n")


if __name__ == "__main__":
    main()
